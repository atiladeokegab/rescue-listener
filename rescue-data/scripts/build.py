"""Rebuild every Rescue Listener data file: knocks, synthetic beds, trial sequences, demo clips, manifest.

Run from the folder root:  uv run python scripts/build.py
The knock zip is untrusted data: it is fetched with curl into its own folder, checked by sha256 and read in
memory with zipfile and soundfile; nothing is extracted or executed. Everything else comes from fixed seeds.
"""
import collections
import hashlib
import io
import json
import pathlib
import subprocess
import zipfile

import numpy as np
import soundfile as sf
from scipy.signal import butter, find_peaks, resample_poly, sosfilt

ROOT = pathlib.Path(__file__).resolve().parent.parent
SR = 16000
KNOCK_RECORD = "https://zenodo.org/records/3668503"
KNOCK_URL = ("https://zenodo.org/api/records/3668503/files/"
             "Knocking%20Sound%20Effects%20With%20Emotional%20Intentions.zip/content")
KNOCK_SHA256 = "5279bee500b5e39ef0ae5a19b60973045923bc33b144344985725c226c16cb84"
KNOCK_ZIP = pathlib.Path.home() / "incoming/rescue-listener/knocks/zip/knocks.zip"
KNOCK_LICENCE = "CC-BY-4.0"
SYNTH_LICENCE = "none: synthetic, generated by scripts/build.py from fixed seeds"

N_KNOCKS = 20
PER_EMOTION = 5                 # variety cap: anger and fear recordings are mostly clipped
CLIP_S = 4.0                    # every trial clip has the same length, so duration can't separate the classes
SNRS = (10, 0, -10)
N_PER_CLASS = 200
MIN_GAP_S = 0.06                # matches biocomp-spine rhythm.MIN_GAP_S
MAX_SPAN_S = 3.5                # under biocomp-spine rhythm.MAX_SPAN_S (4.0)
PATTERNS = ("sos", "motif3", "pair22")
N_FIVE_TAP = 67                 # five_tap_reply trials added after the first N_PER_CLASS, one per old pattern share
BEDS = {"rotor": "synthetic debris impacts + settling grit + drone rotor hum (hovering drone)",
        "rotor_off": "synthetic debris impacts + settling grit + distant machinery, no rotor hum (landed node)"}
PEAK = 10 ** (-1 / 20)          # -1 dBFS


def snr_dir(snr):
    return f"snr{snr:+d}" if snr else "snr0"


# ---- knocks -------------------------------------------------------------------------------------
def fetch_knocks():
    if not KNOCK_ZIP.exists():
        KNOCK_ZIP.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["timeout", "120", "curl", "-fL", "-o", str(KNOCK_ZIP), KNOCK_URL], check=True)
    digest = hashlib.sha256(KNOCK_ZIP.read_bytes()).hexdigest()
    assert digest == KNOCK_SHA256, f"knock zip sha256 {digest} != {KNOCK_SHA256}"


def fade(x, in_s=0.001, out_s=0.01):
    a, b = int(in_s * SR), int(out_s * SR)
    x = x.copy()
    x[:a] *= np.linspace(0, 1, a)
    x[-b:] *= np.cos(np.linspace(0, np.pi / 2, b))
    return x


def pick_knocks():
    """First knock of each recorded action, kept if unclipped, isolated (>= 150 ms to the next knock) and
    decayed to -40 dB within 100 ms. The N_KNOCKS crispest win, at most PER_EMOTION per emotion."""
    z = zipfile.ZipFile(KNOCK_ZIP)
    cands = collections.defaultdict(list)
    for name in sorted(n for n in z.namelist() if n.lower().endswith(".wav")):
        x, sr = sf.read(io.BytesIO(z.read(name)), always_2d=True)
        x = x.mean(axis=1)
        if sr != 48000:
            continue
        env = np.convolve(np.abs(x), np.ones(96) / 96, "same")
        pk, _ = find_peaks(env, height=0.2 * env.max(), distance=int(0.08 * sr))
        if len(pk) < 2 or (pk[1] - pk[0]) / sr < 0.15:
            continue
        quiet = np.flatnonzero(env[pk[0]:pk[1]] < env[pk[0]] * 0.01)
        if not len(quiet) or quiet[0] / sr > 0.1:
            continue
        start = max(0, pk[0] - int(0.005 * sr))
        end = min(pk[0] + quiet[0] + int(0.02 * sr), pk[1] - int(0.005 * sr))
        if (np.abs(x[start:end]) >= 0.999).sum() > 2:  # clipped
            continue
        cands[name.split("/")[-2]].append((quiet[0] / sr, name, x[start:end]))
    best = sorted(c for e in cands.values() for c in sorted(e, key=lambda c: c[0])[:PER_EMOTION])[:N_KNOCKS]
    out = []
    for _, name, seg in sorted(best, key=lambda c: c[1]):
        y = fade(resample_poly(seg, 1, 3))
        out.append((name.split("/", 1)[1], y / np.abs(y).max() * PEAK))
    return out


# ---- synthetic beds -----------------------------------------------------------------------------
def bandpass(x, lo, hi):
    return sosfilt(butter(2, [lo, min(hi, SR / 2 - 100)], btype="band", fs=SR, output="sos"), x)


def rms(x):
    return np.sqrt(np.mean(x ** 2))


def debris_bed(rng, n):
    """Falling debris: Poisson-timed impacts, each band-passed noise with an exponential decay,
    over a settling-grit bed (modulated high-band hiss plus sparse tiny clicks)."""
    t = np.arange(n) / SR
    out = np.zeros(n)
    for _ in range(rng.poisson(2.5 * n / SR)):
        length, i, f = int(rng.uniform(0.03, 0.25) * SR), rng.integers(0, n), rng.uniform(150, 2500)
        burst = bandpass(rng.standard_normal(length), f / 1.6, f * 1.6)
        burst *= np.exp(-np.arange(length) / (rng.uniform(0.01, 0.08) * SR)) * rng.lognormal(0, 0.6)
        out[i:i + length] += burst[:n - i]
    out /= max(rms(out), 1e-9)
    swell = 1 + 0.5 * np.sin(2 * np.pi * rng.uniform(0.1, 0.4) * t + rng.uniform(0, 2 * np.pi))
    grit = bandpass(rng.standard_normal(n), 2000, 6000) * swell
    clicks = bandpass((rng.random(n) < 40 / SR) * rng.standard_normal(n), 1500, 7000)
    return out + 0.3 * grit / rms(grit) + 0.2 * clicks / max(rms(clicks), 1e-9)


def rotor_hum(rng, n):
    """Drone rotor: blade-pass fundamental in 100-200 Hz with harmonics, slow pitch wobble and flutter."""
    t = np.arange(n) / SR
    f0 = rng.uniform(100, 200)
    drift = np.cumsum(rng.standard_normal(n)) / np.sqrt(n)        # slow random walk, about +-1
    wobble = 1 + 0.01 * np.sin(2 * np.pi * rng.uniform(0.2, 0.7) * t + rng.uniform(0, 2 * np.pi)) + 0.004 * drift
    phase = 2 * np.pi * np.cumsum(f0 * wobble) / SR
    x = sum(a * np.sin(h * phase + rng.uniform(0, 2 * np.pi))
            for h, a in ((1, 1.0), (2, 0.5), (3, 0.3), (4, 0.15), (5, 0.08)))
    x *= 1 + 0.1 * np.sin(2 * np.pi * rng.uniform(3, 8) * t)
    wash = bandpass(rng.standard_normal(n), 80, 1500)
    return x / rms(x) + 0.3 * wash / rms(wash)


def machinery(rng, n):
    """Distant machinery: a diesel engine's firing rumble (25-45 Hz with harmonics), slow load swells,
    and low-band noise; distance has already taken the highs off."""
    t = np.arange(n) / SR
    f0 = rng.uniform(25, 45)
    phase = 2 * np.pi * np.cumsum(f0 * (1 + 0.02 * np.sin(2 * np.pi * rng.uniform(0.05, 0.2) * t))) / SR
    x = sum(a * np.sin(h * phase + rng.uniform(0, 2 * np.pi))
            for h, a in ((1, 1.0), (2, 0.6), (3, 0.4), (4, 0.25), (6, 0.15)))
    x *= 1 + 0.3 * np.sin(2 * np.pi * rng.uniform(0.05, 0.15) * t + rng.uniform(0, 2 * np.pi))
    rumble = bandpass(rng.standard_normal(n), 30, 300)
    return x / rms(x) + 0.5 * rumble / rms(rumble)


def bed(seed, n, kind="rotor_off"):
    rng = np.random.default_rng([seed, 1])
    d = debris_bed(rng, n)
    if kind == "rotor":
        r = rotor_hum(rng, n)
        return d / rms(d) + 0.7 * r / rms(r)
    m = machinery(rng, n)
    return d / rms(d) + 0.5 * m / rms(m)


# ---- sequences ----------------------------------------------------------------------------------
def survivor(rng, pattern):
    """Offsets in s from the first knock. Timings follow biocomp-spine rhythm.survivor."""
    tempo = rng.uniform(0.85, 1.2)
    if pattern == "sos":            # 3 knocks with short gaps, 3 with long gaps, 3 with short gaps
        gaps = [0.12, 0.12, 0.36, 0.3, 0.3, 0.36, 0.12, 0.12]
    elif pattern == "motif3":       # one 3-knock motif, played 3 times
        a, b, pause = rng.uniform(0.1, 0.3), rng.uniform(0.1, 0.3), rng.uniform(0.3, 0.45)
        gaps = [a, b, pause, a, b, pause, a, b]
    elif pattern == "five_tap_reply":  # reply to "tap five times": 5 even taps, base gap 0.4-0.7 s after tempo
        gaps = [rng.uniform(0.4, 0.7) / tempo] * 4
    else:                           # 2-2: pairs of knocks, 3 or 4 pairs
        w, pause = rng.uniform(0.1, 0.2), rng.uniform(0.35, 0.5)
        gaps = ([w, pause] * int(rng.integers(3, 5)))[:-1]
    g = np.maximum(np.array(gaps) * tempo * rng.normal(1, 0.06, len(gaps)), MIN_GAP_S)
    return np.concatenate([[0], np.cumsum(g)])


def debris(rng, n, span):
    while True:  # uniform times over the span = Poisson conditioned on the count
        t = np.sort(np.concatenate([[0, span], rng.uniform(0, span, n - 2)]))
        if np.diff(t).min() >= MIN_GAP_S:
            return t


def trial(rng, cls, pattern, seed, offsets, n_knocks, bed_kind):
    span = offsets[-1]
    onset = rng.uniform(0.25, CLIP_S - 0.25 - span - 0.15)
    return dict(id=f"{cls[0]}{seed % 1000:03d}", **{"class": cls}, pattern=pattern, seed=seed, bed=bed_kind,
                n_knocks=len(offsets), span_ms=round(span * 1000, 1), clip_onset_ms=round(onset * 1000, 1),
                knock_times_ms=[round(o * 1000, 1) for o in offsets],
                knock_ids=rng.integers(0, n_knocks, len(offsets)).tolist(),
                gains=np.round(rng.uniform(0.6, 1.0, len(offsets)), 3).tolist())


def make_trials(n_knocks):
    trials = []
    for i in range(N_PER_CLASS + N_FIVE_TAP):
        # the first N_PER_CLASS trials are unchanged; the node-story trials follow on the rotor-off bed
        pattern, bed_kind = (PATTERNS[i % len(PATTERNS)], "rotor") if i < N_PER_CLASS else ("five_tap_reply", "rotor_off")
        rng = np.random.default_rng(1000 + i)
        s = trial(rng, "survivor", pattern, 1000 + i, survivor(rng, pattern), n_knocks, bed_kind)
        rng = np.random.default_rng(2000 + i)
        d = trial(rng, "debris", "poisson", 2000 + i, debris(rng, s["n_knocks"], s["span_ms"] / 1000), n_knocks,
                  bed_kind)
        s["matched_to"], d["matched_to"] = d["id"], s["id"]
        trials += [s, d]
    return trials


def self_check(trials):
    by = {c: [t for t in trials if t["class"] == c] for c in ("survivor", "debris")}
    assert len(by["survivor"]) == len(by["debris"]) == N_PER_CLASS + N_FIVE_TAP
    beds = {c: collections.Counter(t["bed"] for t in ts) for c, ts in by.items()}
    assert beds["survivor"] == beds["debris"], beds                 # nor can the bed
    for t in by["survivor"]:
        if t["pattern"] == "five_tap_reply":
            g = np.diff(t["knock_times_ms"]) / 1000
            assert t["n_knocks"] == 5 and 0.4 * 0.8 < g.min() and g.max() < 0.7 * 1.2, t["id"]  # 6% jitter, 3+ sigma
    counts = {c: collections.Counter(t["n_knocks"] for t in ts) for c, ts in by.items()}
    assert counts["survivor"] == counts["debris"], counts           # count alone can't separate the classes
    spans = {c: sorted(t["span_ms"] for t in ts) for c, ts in by.items()}
    assert np.allclose(spans["survivor"], spans["debris"], atol=0.11), "spans differ"  # nor can duration
    for t in trials:
        assert t["span_ms"] <= MAX_SPAN_S * 1000 and min(np.diff(t["knock_times_ms"])) >= MIN_GAP_S * 1000 - 0.1
    return counts["survivor"]


# ---- rendering ----------------------------------------------------------------------------------
def render(n, knock_times_s, knock_ids, gains, knocks, seed, snr, bed_kind="rotor_off"):
    """Knocks placed at the given clip times over the synthetic bed. SNR is measured where knocks sound:
    knock power over bed power on the samples covered by a knock."""
    sig, mask = np.zeros(n), np.zeros(n, bool)
    for t, k, g in zip(knock_times_s, knock_ids, gains):
        i = int(round(t * SR))
        y = knocks[k][:n - i] * g
        sig[i:i + len(y)] += y
        mask[i:i + len(y)] = True
    b = bed(seed, n, bed_kind)
    if snr is None:
        mix = b
    else:
        b *= np.sqrt(np.mean(sig[mask] ** 2) / np.mean(b[mask] ** 2) / 10 ** (snr / 10))
        mix = sig + b
    return mix / np.abs(mix).max() * PEAK


def write(path, x):
    path.parent.mkdir(parents=True, exist_ok=True)
    sf.write(path, x, SR, subtype="PCM_16")


# ---- manifest -----------------------------------------------------------------------------------
def describe(rel):
    """(licence, source_url, synthetic) for a file. synthetic is 'mixed' for real knocks over synthetic beds."""
    if rel.startswith("knocks/"):
        return KNOCK_LICENCE, KNOCK_RECORD, False
    if rel.startswith("synth/") or rel in ("sequences.json", "demo/debris_only.wav", "demo/node_debris_only.wav"):
        return SYNTH_LICENCE, None, True
    if rel.startswith(("sequences/", "demo/")):
        return KNOCK_LICENCE + " (knocks adapted from source) + synthetic bed", KNOCK_RECORD, "mixed"
    if rel == "survival.json":
        return "facts with one-sentence quotes; see each claim's source", "see source_url per claim", False
    return "project file", None, False


def manifest():
    files = []
    for p in sorted(ROOT.rglob("*")):
        rel = p.relative_to(ROOT).as_posix()
        if p.is_dir() or rel.split("/")[0] in (".git", ".venv") or "__pycache__" in rel or rel == "manifest.json":
            continue
        licence, source, synthetic = describe(rel)
        files.append(dict(path=rel, bytes=p.stat().st_size, sha256=hashlib.sha256(p.read_bytes()).hexdigest(),
                          licence=licence, source_url=source, synthetic=synthetic))
    (ROOT / "manifest.json").write_text(json.dumps(dict(
        knock_download=dict(url=KNOCK_URL, record=KNOCK_RECORD, sha256=KNOCK_SHA256, licence=KNOCK_LICENCE),
        files=files), indent=1) + "\n")
    return files


def main():
    fetch_knocks()
    picked = pick_knocks()
    assert len(picked) == N_KNOCKS, len(picked)
    knocks = [y for _, y in picked]
    for i, (_, y) in enumerate(picked):
        write(ROOT / f"knocks/knock_{i:02d}.wav", y)

    for s in range(3):
        n = int(8 * SR)
        d, r = debris_bed(np.random.default_rng([90 + s, 1]), n), rotor_hum(np.random.default_rng([90 + s, 2]), n)
        write(ROOT / f"synth/synthetic_debris_bed_seed{90 + s}.wav", d / np.abs(d).max() * PEAK)
        write(ROOT / f"synth/synthetic_rotor_hum_seed{90 + s}.wav", r / np.abs(r).max() * PEAK)
        m = machinery(np.random.default_rng([90 + s, 3]), n)
        write(ROOT / f"synth/synthetic_distant_machinery_seed{90 + s}.wav", m / np.abs(m).max() * PEAK)

    trials = make_trials(len(knocks))
    count_dist = self_check(trials)
    n = int(CLIP_S * SR)
    for t in trials:
        times = (np.array(t["knock_times_ms"]) + t["clip_onset_ms"]) / 1000
        t["files"] = {}
        for snr in SNRS:
            rel = f"sequences/{snr_dir(snr)}/{t['id']}.wav"
            write(ROOT / rel, render(n, times, t["knock_ids"], t["gains"], knocks, t["seed"], snr, t["bed"]))
            t["files"][snr_dir(snr)] = rel

    # showcase clips, 8 s: the survivor knocks SOS twice, as a buried survivor repeats it
    rng = np.random.default_rng(77)
    sos = survivor(rng, "sos")
    times = np.concatenate([1.0 + sos, 4.6 + sos])
    ids, gains = rng.integers(0, len(knocks), len(times)).tolist(), np.round(rng.uniform(0.6, 1, len(times)), 3).tolist()
    n8 = int(8 * SR)
    demos = []
    for rel, snr, kt in (("demo/survivor_buried_snr-10.wav", -10, times), ("demo/debris_only.wav", None, []),
                         ("demo/survivor_snr0.wav", 0, times)):
        write(ROOT / rel, render(n8, kt, ids, gains, knocks, 77, snr, "rotor"))
        demos.append(dict(file=rel, snr_db=snr, seed=77, knock_clip_times_ms=[round(x * 1000, 1) for x in kt],
                          **{"class": "survivor" if len(kt) else "debris"}, pattern="sos x2" if len(kt) else "bed only",
                          bed="rotor"))

    # node clips, 8 s on the rotor-off bed: a reply to "tap five times", then repeated once after a pause
    rng = np.random.default_rng(78)
    first = survivor(rng, "five_tap_reply")
    second = first[-1] + rng.uniform(1.0, 1.5) + survivor(rng, "five_tap_reply")
    times = 0.8 + np.concatenate([first, second])
    assert times[-1] < 7.8, times
    ids, gains = rng.integers(0, len(knocks), len(times)).tolist(), np.round(rng.uniform(0.6, 1, len(times)), 3).tolist()
    for rel, snr, kt in (("demo/node_five_tap_reply_snr0.wav", 0, times), ("demo/node_debris_only.wav", None, [])):
        write(ROOT / rel, render(n8, kt, ids, gains, knocks, 78, snr, "rotor_off"))
        demos.append(dict(file=rel, snr_db=snr, seed=78, knock_clip_times_ms=[round(x * 1000, 1) for x in kt],
                          **{"class": "survivor" if len(kt) else "debris"},
                          pattern="five_tap_reply x2" if len(kt) else "bed only", bed="rotor_off"))

    (ROOT / "sequences.json").write_text(json.dumps(dict(
        meta=dict(synthetic=True, generator="scripts/build.py", sample_rate=SR, clip_s=CLIP_S, snr_db=list(SNRS),
                  snr_definition="10*log10(knock power / bed power) over the samples where a knock sounds",
                  knock_times="knock_times_ms are offsets from the first knock; the first knock sits at "
                              "clip_onset_ms in the WAV",
                  classes="survivor = SOS, repeated 3-knock motif, 2-2 pairs or five_tap_reply (5 even taps, "
                          "gap about 0.4-0.7 s, the reply to a rescuer's 'tap five times'; the repeat after a pause "
                          "only fits the 8 s demo clips); debris = the same number of "
                          "knocks at uniform random (Poisson conditioned on count) times over the same span. Both "
                          "classes use the same knock pool and gain range, so only timing differs.",
                  knock_count_distribution={str(k): v for k, v in sorted(count_dist.items())},
                  bed="per trial in trials[].bed (see beds); rotor = synthetic debris impacts + settling grit + "
                      "drone rotor hum, seeded [seed, 1]",
                  beds=BEDS, default_bed="rotor_off",
                  bed_note="the first 400 trials keep the rotor bed; five_tap_reply trials and their debris matches "
                           "use rotor_off, matched pairs share a bed so the bed can't separate the classes"),
        knock_pool=[dict(file=f"knocks/knock_{i:02d}.wav", source_file=name) for i, (name, _) in enumerate(picked)],
        trials=trials, demo=demos), indent=1) + "\n")

    files = manifest()
    print(f"{len(files)} files, {sum(f['bytes'] for f in files) / 1e6:.1f} MB; knock counts {dict(count_dist)}")


if __name__ == "__main__":
    main()
